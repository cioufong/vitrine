#!/usr/bin/env python3
"""Regenerates Sources/VitrineQEMU/MicrosoftSecureBootCerts.swift from DER certificates downloaded
from Microsoft's official repository (https://github.com/microsoft/secureboot_objects, files under
PreSignedObjects/{KEK,DB}/Certificates). Usage: make-secureboot-certs.py <dir with the .der files>"""
import base64, hashlib, os, sys

KEK = ["MicCorKEKCA2011_2011-06-24.der", "microsoft corporation kek 2k ca 2023.der"]
DB = ["MicWinProPCA2011_2011-10-19.der", "windows uefi ca 2023.der", "MicCorUEFCA2011_2011-06-27.der",
      "microsoft uefi ca 2023.der", "microsoft option rom uefi ca 2023.der"]

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), "../../Sources/VitrineQEMU/MicrosoftSecureBootCerts.swift")

def entry(name):
    data = open(os.path.join(src, name), "rb").read()
    b64 = base64.b64encode(data).decode()
    lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    body = ",\n".join(f'        "{l}"' for l in lines)
    return (f'    // {name}\n    // SHA-256 {hashlib.sha256(data).hexdigest()}\n'
            f'    Certificate(name: "{name}", der: [\n{body},\n    ].joined()),\n')

with open(out, "w") as f:
    f.write("// Generated by scripts/dev/make-secureboot-certs.py from Microsoft's public Secure Boot CA\n")
    f.write("// certificates (github.com/microsoft/secureboot_objects). Do not edit by hand.\n\n")
    f.write("enum MicrosoftSecureBootCerts {\n")
    f.write("    struct Certificate { let name: String; let der: String }\n\n")
    f.write("    /// Key exchange keys: Microsoft Corporation KEK CA 2011 and KEK 2K CA 2023.\n")
    f.write("    static let kek: [Certificate] = [\n" + "".join(entry(n) for n in KEK) + "    ]\n\n")
    f.write("    /// Allowed signers (db): Windows Production PCA 2011 and Windows UEFI CA 2023 (Windows),\n")
    f.write("    /// Microsoft UEFI CA 2011/2023 (third-party loaders such as Linux shim), Option ROM UEFI CA 2023.\n")
    f.write("    static let db: [Certificate] = [\n" + "".join(entry(n) for n in DB) + "    ]\n")
    f.write("}\n")
print("wrote", os.path.normpath(out))
