// Scancode is a set-1 make code plus whether it needs KEYEVENTF_EXTENDEDKEY.
type Scancode struct {
	Code     uint16
	Extended bool
}

// Set-1 scancodes for the modifiers the agent synthesizes itself.
var (
	scLeftShift = Scancode{0x2A, false}
	scLeftCtrl  = Scancode{0x1D, false}
	scRightCtrl = Scancode{0x1D, true}
	scLeftAlt   = Scancode{0x38, false}
	scLeftWin   = Scancode{0x5B, true}
	scCapsLock  = Scancode{0x3A, false}
)

// ScancodeFor maps a macOS key code to the scancode SendInput should send.
// In CommandAsControl mode (the Windows default) ⌘ becomes Ctrl so Mac
// shortcuts (⌘C, ⌘V…) do what Windows users expect.
func ScancodeFor(vk uint16, mode keymap.CommandMode) (Scancode, bool) {
	if mode == keymap.CommandAsControl {
		switch vk {
		case keymap.VKCommand:
			return scLeftCtrl, true
		case keymap.VKRightCommand:
			return scRightCtrl, true
		}
	}
	c, ok := macToSet1[vk]
	if !ok {
		return Scancode{}, false
	}
	sc := Scancode{Code: c & 0x7F, Extended: c&0x80 != 0}
	// Windows treats scancode 0x45 without E0 as Pause; Num Lock (the Mac
	// keypad Clear key sits there) needs the extended flag.
	if sc.Code == 0x45 {
		sc.Extended = true
	}
	return sc, true
}

// modifierScancode is the key the agent presses to satisfy a host modifier flag.
func modifierScancode(flag uint64, mode keymap.CommandMode) Scancode {
	switch flag {
	case keymap.FlagShift:
		return scLeftShift
	case keymap.FlagControl:
		return scLeftCtrl
	case keymap.FlagOption:
		return scLeftAlt
	case keymap.FlagCommand:
		if mode == keymap.CommandAsControl {
			return scLeftCtrl
		}
		return scLeftWin
	}
	return Scancode{}
}
