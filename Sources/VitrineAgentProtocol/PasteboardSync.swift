import AppKit

/// Two-way clipboard sync used by both host and guest: watches the local general pasteboard and
/// applies remote content, suppressing echoes via content fingerprints.
public final class PasteboardSync {
    /// UTIs synchronized, in preference order. Files are not synced (use shared folders).
    public static let syncedTypes: [NSPasteboard.PasteboardType] = [
        .string, .rtf, .html, .png, .tiff, .URL,
    ]
    /// Largest clipboard content sent or accepted, all synced types together.
    public static let maxBytes = 32 << 20
    /// Markers apps put on pasteboard content that must not leave the Mac or be kept
    /// (nspasteboard.org): passwords from password managers (concealed), one-off content such as
    /// one-time codes (transient), and content an app put there without the user copying it.
    public static let privateMarkerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var lastFingerprint: Int?
    private var timer: Timer?
    public var onLocalChange: ((ClipboardContent) -> Void)?

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
    }

    public func start(interval: TimeInterval = 0.3) {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { [weak self] _ in self?.poll() }
    }

    public func stop() { timer?.invalidate(); timer = nil }

    public var isRunning: Bool { timer != nil }

    /// Hands the current contents to `onLocalChange` even if they were sent before (the echo filter
    /// is for polling), e.g. when the other side may now have it. Polling then only reports changes
    /// made after this.
    public func sendCurrent() {
        lastChangeCount = pasteboard.changeCount
        guard let content = snapshot() else { return }
        lastFingerprint = content.fingerprint
        onLocalChange?(content)
    }

    /// Reads the current pasteboard contents; nil when there is nothing to share, including
    /// content marked private (`privateMarkerTypes`).
    public func snapshot() -> ClipboardContent? {
        guard let item = pasteboard.pasteboardItems?.first else { return nil }
        let marked = (pasteboard.types ?? []) + item.types
        guard !marked.contains(where: { Self.privateMarkerTypes.contains($0.rawValue) }) else { return nil }
        var items: [ClipboardContent.Item] = []
        var total = 0
        for type in Self.syncedTypes where item.types.contains(type) {
            guard let data = item.data(forType: type) else { continue }
            total += data.count
            if total > Self.maxBytes { break }
            items.append(.init(type: type.rawValue, data: data))
        }
        return items.isEmpty ? nil : ClipboardContent(items: items)
    }

    func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard let content = snapshot() else { return }
        let fp = content.fingerprint
        guard fp != lastFingerprint else { return }
        lastFingerprint = fp
        onLocalChange?(content)
    }

    /// Writes content that arrived from the other side. Content of no synced type, or larger than
    /// `maxBytes` in its synced types, is dropped and the pasteboard left alone: returns false.
    @discardableResult
    public func apply(_ content: ClipboardContent) -> Bool {
        let synced = Set(Self.syncedTypes.map(\.rawValue))
        let entries = content.items.filter { synced.contains($0.type) }
        guard !entries.isEmpty, entries.reduce(0, { $0 + $1.data.count }) <= Self.maxBytes else { return false }
        let fp = content.fingerprint
        guard fp != lastFingerprint else { return true }
        lastFingerprint = fp
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        for entry in entries {
            item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type))
        }
        pasteboard.writeObjects([item])
        lastChangeCount = pasteboard.changeCount
        return true
    }
}
