/// The Mac clipboard reaches a VM only while that VM's window is focused, and the guest may set the
/// Mac clipboard only then or just after (copy in the guest, switch to a Mac app, paste).
final class ClipboardFocusGateTests: XCTestCase {
    let t0 = Date(timeIntervalSinceReferenceDate: 1_000_000)

    func testUnfocusedByDefault() {
        let gate = ClipboardFocusGate()
        XCTAssertFalse(gate.isFocused)
        XCTAssertFalse(gate.allowsSending)
        XCTAssertFalse(gate.acceptsGuestClipboard(at: t0), "a VM that was never focused can't set the Mac clipboard")
    }

    func testFocusedSendsAndAccepts() {
        var gate = ClipboardFocusGate()
        XCTAssertTrue(gate.setFocused(true, at: t0), "gaining focus is a change")
        XCTAssertTrue(gate.allowsSending)
        XCTAssertTrue(gate.acceptsGuestClipboard(at: t0.addingTimeInterval(3600)))
        XCTAssertFalse(gate.setFocused(true, at: t0.addingTimeInterval(1)), "already focused: no change")
    }

    func testLosingFocusStopsSendingAndLeavesAGraceWindow() {
        var gate = ClipboardFocusGate()
        gate.setFocused(true, at: t0)
        XCTAssertTrue(gate.setFocused(false, at: t0.addingTimeInterval(10)))
        XCTAssertFalse(gate.allowsSending)
        XCTAssertTrue(gate.acceptsGuestClipboard(at: t0.addingTimeInterval(10)))
        XCTAssertTrue(gate.acceptsGuestClipboard(at: t0.addingTimeInterval(11.9)))
        XCTAssertFalse(gate.acceptsGuestClipboard(at: t0.addingTimeInterval(12.1)), "grace is about 2 s")
        XCTAssertFalse(gate.acceptsGuestClipboard(at: t0.addingTimeInterval(9)), "a clock going backwards grants nothing")
    }

    func testRepeatedUnfocusDoesNotExtendTheGrace() {
        var gate = ClipboardFocusGate()
        gate.setFocused(true, at: t0)
        gate.setFocused(false, at: t0.addingTimeInterval(1))
        XCTAssertFalse(gate.setFocused(false, at: t0.addingTimeInterval(2.5)), "already unfocused: no change")
        XCTAssertFalse(gate.acceptsGuestClipboard(at: t0.addingTimeInterval(3.5)))
    }

    func testCustomGrace() {
        var gate = ClipboardFocusGate(grace: 0)
        gate.setFocused(true, at: t0)
        gate.setFocused(false, at: t0)
        XCTAssertFalse(gate.acceptsGuestClipboard(at: t0.addingTimeInterval(0.01)))
    }
}

final class PasteboardSyncFilterTests: XCTestCase {
    private var pasteboards: [NSPasteboard] = []

    private func makePasteboard() -> NSPasteboard {
        let pb = NSPasteboard.withUniqueName()
        pasteboards.append(pb)
        return pb
    }

    override func tearDown() {
        for pb in pasteboards { pb.releaseGlobally() }
        pasteboards = []
        super.tearDown()
    }

    private func write(_ pb: NSPasteboard, _ text: String, marker: NSPasteboard.PasteboardType? = nil) {
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if let marker { item.setData(Data(), forType: marker) }
        pb.writeObjects([item])
    }

    func testPlainTextIsSnapshotted() {
        let pb = makePasteboard()
        write(pb, "hello")
        let sync = PasteboardSync(pasteboard: pb)
        XCTAssertEqual(sync.snapshot()?.items.first.map { String(decoding: $0.data, as: UTF8.self) }, "hello")
    }

    /// Password managers mark secrets (nspasteboard.org): those never leave the Mac.
    func testConcealedTransientAndAutoGeneratedItemsAreNeverSnapshotted() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            let pb = makePasteboard()
            write(pb, "s3cret", marker: NSPasteboard.PasteboardType(marker))
            let sync = PasteboardSync(pasteboard: pb)
            XCTAssertNil(sync.snapshot(), "\(marker) content must not be read for sharing")
            var sent: [ClipboardContent] = []
            sync.onLocalChange = { sent.append($0) }
            sync.sendCurrent()
            XCTAssertTrue(sent.isEmpty, "\(marker) content must not be sent")
        }
    }

    func testPollSkipsConcealedChanges() {
        let pb = makePasteboard()
        let sync = PasteboardSync(pasteboard: pb)
        var sent: [ClipboardContent] = []
        sync.onLocalChange = { sent.append($0) }
        write(pb, "s3cret", marker: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        sync.poll()
        XCTAssertTrue(sent.isEmpty)
        write(pb, "public")
        sync.poll()
        XCTAssertEqual(sent.count, 1)
    }

    /// Sending on focus must not be swallowed by the echo filter: the same content may have been
    /// sent before, or consumed by a poll while the VM wasn't focused.
    func testSendCurrentBypassesTheEchoFilter() {
        let pb = makePasteboard()
        let sync = PasteboardSync(pasteboard: pb)
        var sent: [ClipboardContent] = []
        sync.onLocalChange = { sent.append($0) }
        write(pb, "address")
        sync.poll()
        XCTAssertEqual(sent.count, 1)
        sync.sendCurrent()
        XCTAssertEqual(sent.count, 2)
        sync.poll()
        XCTAssertEqual(sent.count, 2, "no change since: the poll sends nothing more")
    }

    func testApplyWritesSyncedTypes() {
        let pb = makePasteboard()
        let sync = PasteboardSync(pasteboard: pb)
        let ok = sync.apply(ClipboardContent(items: [.init(type: NSPasteboard.PasteboardType.string.rawValue, data: Data("from guest".utf8))]))
        XCTAssertTrue(ok)
        XCTAssertEqual(pb.string(forType: .string), "from guest")
    }

    func testApplyRefusesOversizedContent() {
        let pb = makePasteboard()
        write(pb, "keep me")
        let sync = PasteboardSync(pasteboard: pb)
        let big = Data(count: PasteboardSync.maxBytes / 2 + 1)
        let content = ClipboardContent(items: [.init(type: NSPasteboard.PasteboardType.png.rawValue, data: big),
                                               .init(type: NSPasteboard.PasteboardType.tiff.rawValue, data: big)])
        XCTAssertFalse(sync.apply(content), "more than maxBytes in total is dropped")
        XCTAssertEqual(pb.string(forType: .string), "keep me", "the Mac clipboard is left alone")
    }

    func testApplyIgnoresUnsyncedTypesWhenSizing() {
        let pb = makePasteboard()
        let sync = PasteboardSync(pasteboard: pb)
        let content = ClipboardContent(items: [.init(type: "com.example.junk", data: Data(count: PasteboardSync.maxBytes + 1)),
                                               .init(type: NSPasteboard.PasteboardType.string.rawValue, data: Data("ok".utf8))])
        XCTAssertTrue(sync.apply(content))
        XCTAssertEqual(pb.string(forType: .string), "ok")
        XCTAssertNil(pb.data(forType: NSPasteboard.PasteboardType("com.example.junk")))
    }

    func testApplyOfOnlyUnsyncedTypesLeavesTheClipboardAlone() {
        let pb = makePasteboard()
        write(pb, "keep me")
        let sync = PasteboardSync(pasteboard: pb)
        XCTAssertFalse(sync.apply(ClipboardContent(items: [.init(type: "com.example.junk", data: Data("x".utf8))])))
        XCTAssertEqual(pb.string(forType: .string), "keep me")
    }
}

/// A seamless guest reports which of its windows is focused; that may move the Mac's key window
/// between that VM's own windows, not take it from another VM or Vitrine window (which would also
/// hand that guest the Mac clipboard).
final class CoherenceKeyStealTests: XCTestCase {
    func testGuestMayOnlyMoveKeyAmongItsOwnWindows() {
        XCTAssertTrue(CoherenceController.guestMayTakeKey(keyWindowExists: true, keyWindowIsOurs: true, entering: false))
        XCTAssertFalse(CoherenceController.guestMayTakeKey(keyWindowExists: true, keyWindowIsOurs: false, entering: false))
        XCTAssertTrue(CoherenceController.guestMayTakeKey(keyWindowExists: false, keyWindowIsOurs: false, entering: false))
    }

    /// Entering seamless mode is the user's choice: the guest's focused window then becomes key even
    /// though the hidden display window handed key to another Vitrine window meanwhile.
    func testEnteringSeamlessModeMayTakeKey() {
        XCTAssertTrue(CoherenceController.guestMayTakeKey(keyWindowExists: true, keyWindowIsOurs: false, entering: true))
    }
}
